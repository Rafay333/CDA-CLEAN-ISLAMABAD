IF OBJECT_ID('Employees','U') IS NULL CREATE TABLE Employees(
    Id INT IDENTITY PRIMARY KEY, Code NVARCHAR(50) NOT NULL UNIQUE, Name NVARCHAR(200) NOT NULL,
    Department NVARCHAR(200) NULL, Active INT NOT NULL DEFAULT 1, FaceImage VARBINARY(MAX) NULL, FaceEncoding VARBINARY(MAX) NULL);
IF OBJECT_ID('Locations','U') IS NULL CREATE TABLE Locations(
    Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(200) NOT NULL, Lat FLOAT NOT NULL, Lng FLOAT NOT NULL, RadiusM FLOAT NOT NULL DEFAULT 100);
IF OBJECT_ID('EmployeeLocations','U') IS NULL CREATE TABLE EmployeeLocations(
    EmployeeId INT NOT NULL, LocationId INT NOT NULL, PRIMARY KEY(EmployeeId, LocationId));
IF OBJECT_ID('Devices','U') IS NULL CREATE TABLE Devices(
    DeviceId NVARCHAR(100) PRIMARY KEY, OwnerEmployeeId INT NOT NULL, FirstSeen DATETIME2 NOT NULL);
IF OBJECT_ID('Attendance','U') IS NULL CREATE TABLE Attendance(
    Id INT IDENTITY PRIMARY KEY, EmployeeId INT NOT NULL, LocationId INT NOT NULL, Time DATETIME2 NOT NULL,
    Similarity FLOAT NULL, DeviceId NVARCHAR(100) NULL, DeviceOwnerId INT NULL);
